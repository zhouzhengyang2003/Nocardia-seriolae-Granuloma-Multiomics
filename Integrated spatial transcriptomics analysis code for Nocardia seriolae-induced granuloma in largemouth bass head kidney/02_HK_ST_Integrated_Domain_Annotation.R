# ==============================================================================
# --- 10. Cell/domain composition calculation and visualization ---
# ==============================================================================

cell_table <- table(
  CellType = Idents(seu_int_rpca),
  Sample = seu_int_rpca$orig.ident
)

cell_ratio <- prop.table(
  cell_table,
  margin = 2
) %>%
  as.data.frame()

colnames(cell_ratio) <- c(
  "CellType",
  "Sample",
  "Freq"
)

cell_counts <- as.data.frame(cell_table)
colnames(cell_counts) <- c(
  "CellType",
  "Sample",
  "Count"
)

cell_ratio <- merge(
  cell_ratio,
  cell_counts,
  by = c("CellType", "Sample")
)

cell_ratio$CellType <- factor(
  cell_ratio$CellType,
  levels = desired_order
)

cell_ratio <- cell_ratio %>%
  arrange(Sample, CellType)

cell_ratio$LegendLabel <- paste0(
  cell_ratio$CellType,
  " (",
  sprintf("%.1f%%", cell_ratio$Freq * 100),
  ", ",
  cell_ratio$Count,
  ")"
)

p_cell_composition_pie <- ggplot(
  cell_ratio,
  aes(x = "", y = Freq, fill = CellType)
) +
  geom_bar(
    stat = "identity",
    width = 1,
    color = "white"
  ) +
  coord_polar(theta = "y") +
  facet_wrap(~ Sample, nrow = 1) +
  scale_fill_manual(
    values = cluster_colors,
    labels = cell_ratio$LegendLabel
  ) +
  theme_void() +
  labs(
    fill = "Cell Type (Ratio, Count)",
    title = "Cell Composition per Sample"
  ) +
  theme(
    strip.text = element_text(size = 12, face = "bold"),
    legend.title = element_text(size = 11),
    legend.text = element_text(size = 9),
    plot.title = element_text(hjust = 0.5)
  )

print(p_cell_composition_pie)


